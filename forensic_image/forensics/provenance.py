"""Forensic provenance analysis and processing history timeline hypothesis generator.

FORENSIC PRINCIPLE:
Reconstructing processing history from surviving artifacts is an inductive scientific process.
All timeline sequences generated by this module are explicitly designated as:
    FORENSIC HYPOTHESES
They must never be presented as incontrovertible facts.
"""

from typing import Any, Dict, List, Optional, Tuple
from pydantic import BaseModel, Field

from forensic_image.core.constants import ConfidenceLevel, FindingStatus, Severity
from forensic_image.core.findings import Finding
from forensic_image.forensics.base import BaseAnalyzer


class TimelineStep(BaseModel):
    """A discrete hypothesized historical stage in the lifecycle of the digital evidence."""
    step_number: int
    stage_name: str
    description: str
    evidence_basis: List[str] = Field(default_factory=list)
    confidence_level: ConfidenceLevel = ConfidenceLevel.MEDIUM


class ProvenanceHypothesis(BaseModel):
    """Scientifically cautious hypothesis regarding image acquisition and processing sequence."""
    origin_category: str = "UNKNOWN"  # "CAMERA_CAPTURE", "SCREEN_CAPTURE", "GRAPHIC_OR_SYNTHETIC", "UNKNOWN"
    timeline_steps: List[TimelineStep] = Field(default_factory=list)
    confidence: float = 0.50
    confidence_level: ConfidenceLevel = ConfidenceLevel.MEDIUM
    summary_narrative: str = ""
    alternative_hypotheses: List[str] = Field(default_factory=list)
    unresolved_questions: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)


class ProvenanceAnalyzer(BaseAnalyzer):
    """Synthesizes structural, metadata, and statistical evidence into a documented forensic hypothesis."""

    name = "provenance"
    description = "Evidence-driven provenance reconstruction and timeline hypothesis"
    version = "1.0.0"

    def analyze(self, evidence: Any, context: Dict[str, Any]) -> Tuple[Dict[str, Any], List[Finding]]:
        hypothesis = ProvenanceHypothesis()
        findings: List[Finding] = []

        exif = context.get("exif", {})
        xmp = context.get("xmp", {})
        screenshot = context.get("screenshot", {})
        recompression = context.get("recompression", {})
        transformation = context.get("transformation", {})
        tampering = context.get("tampering", {})
        quant = context.get("quantization", {})

        has_camera = bool(exif.get("make") or exif.get("model"))
        is_screenshot = (screenshot.get("status") in ("detected", "possible"))
        is_recompressed = recompression.get("is_recompressed_suspected", False)
        is_downscaled = transformation.get("is_downscaled_suspected", False)
        is_cropped = transformation.get("is_cropped_suspected", False)
        has_editing_sw = tampering.get("editing_software_detected", False)
        software_name = tampering.get("detected_software")

        steps: List[TimelineStep] = []
        step_idx = 1

        # 1. Origin Stage
        if is_screenshot and not has_camera:
            hypothesis.origin_category = "SCREEN_CAPTURE"
            dev = screenshot.get("matched_device", "Digital display device")
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="ORIGIN: Screen Capture",
                    description=f"Evidence created via screenshot capture on a display device consistent with {dev}.",
                    evidence_basis=screenshot.get("evidence_signals", ["Native display resolution", "Lack of camera metadata"]),
                    confidence_level=screenshot.get("confidence_level", ConfidenceLevel.MEDIUM),
                )
            )
            step_idx += 1
        elif has_camera:
            hypothesis.origin_category = "CAMERA_CAPTURE"
            cam = f"{exif.get('make', '')} {exif.get('model', '')}".strip()
            dto = exif.get("date_time_original", "Unknown date")
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="ORIGIN: Physical Camera Capture",
                    description=f"Image captured by physical optical camera hardware ({cam}) on {dto}.",
                    evidence_basis=[
                        f"Camera Make/Model: {cam}",
                        f"Capture timestamp: {dto}",
                        f"Optical parameters: ISO {exif.get('iso')}, FL {exif.get('focal_length_mm')}mm",
                    ],
                    confidence_level=ConfidenceLevel.HIGH,
                )
            )
            step_idx += 1
        else:
            hypothesis.origin_category = "UNKNOWN"
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="ORIGIN: Indeterminate Origin",
                    description="Evidence lacks camera hardware metadata and screen-specific signatures; origin is indeterminate.",
                    evidence_basis=["Absence of camera Make/Model", "Absence of recognized screen resolution"],
                    confidence_level=ConfidenceLevel.LOW,
                )
            )
            step_idx += 1

        # 2. Intermediate Edits / Software Manipulation
        if has_editing_sw:
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="TRANSFORMATION: Software Editing",
                    description=f"Image processed or re-exported using image editing software ({software_name}).",
                    evidence_basis=[f"Software signature: {software_name}"],
                    confidence_level=ConfidenceLevel.HIGH,
                )
            )
            step_idx += 1

        # 3. Resizing / Cropping
        if is_downscaled or is_cropped:
            action_desc = []
            if is_downscaled:
                action_desc.append(f"downscaling (to {transformation.get('actual_width')}x{transformation.get('actual_height')})")
            if is_cropped:
                action_desc.append("cropping (non-standard sensor aspect ratio)")
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="TRANSFORMATION: Spatial Resampling / Cropping",
                    description=f"Image underwent {' and '.join(action_desc)}.",
                    evidence_basis=[
                        f"Pixel dimensions: {transformation.get('actual_width')}x{transformation.get('actual_height')}",
                        f"Aspect ratio: {transformation.get('actual_aspect_ratio')}",
                    ],
                    confidence_level=ConfidenceLevel.MEDIUM,
                )
            )
            step_idx += 1

        # 4. Recompression
        if is_recompressed:
            est_q = quant.get("estimated_quality", "unknown")
            steps.append(
                TimelineStep(
                    step_number=step_idx,
                    stage_name="ENCODING: Secondary JPEG Recompression",
                    description=f"Image recompressed with secondary encoder at estimated quality ~{est_q}%.",
                    evidence_basis=recompression.get("evidence_signals", ["Quantization table / DCT distribution"]),
                    confidence_level=recompression.get("confidence_level", ConfidenceLevel.MEDIUM),
                )
            )
            step_idx += 1

        # Final step: Current supplied file
        steps.append(
            TimelineStep(
                step_number=step_idx,
                stage_name="EVIDENCE: Current State (Supplied File)",
                description=f"Digital evidence acquired as {evidence.format.value} ({evidence.hashes.size_bytes} bytes).",
                evidence_basis=[f"SHA-256: {evidence.hashes.sha256}"],
                confidence_level=ConfidenceLevel.CERTAIN,
            )
        )

        hypothesis.timeline_steps = steps

        # Build summary narrative
        seq_names = [s.stage_name.split(":")[-1].strip() for s in steps]
        hypothesis.summary_narrative = " -> ".join(seq_names)

        # Scientific caveats & limitations
        hypothesis.limitations = [
            "This timeline is an inductive hypothesis constructed from surviving artifacts.",
            "Intermediate states that left no surviving artifacts cannot be inferred.",
            "Stripped metadata cannot be verified or recovered from pixel bytes alone.",
        ]

        hypothesis.alternative_hypotheses = [
            "Intermediate transformations may have occurred in a different sequence than hypothesized.",
            "Camera firmware settings (e.g. low-resolution mode) may mimic post-capture downscaling.",
        ]

        findings.append(
            Finding(
                category="PROVENANCE",
                status=FindingStatus.INFERRED,
                severity=Severity.INFO,
                title="Forensic provenance timeline hypothesis generated",
                description=(
                    f"Generated {len(steps)}-stage processing sequence hypothesis: {hypothesis.summary_narrative}."
                ),
                evidence=[f"Stage count: {len(steps)}", f"Hypothesized origin: {hypothesis.origin_category}"],
                confidence=0.75,
                confidence_level=ConfidenceLevel.MEDIUM,
                limitations=hypothesis.limitations,
                alternative_explanations=hypothesis.alternative_hypotheses,
            )
        )

        return hypothesis.model_dump(), findings
